# scaffolded by appqe v0.16.1 - project-owned, edit freely
"""Fetch a Jira issue's story and acceptance criteria, for QE test generation.

Generated by `appqe scaffold --tool jira`. **This is a starter, not a product** -
it covers the read path QE needs and nothing else. Adapt it to your client's
Jira: field ids for acceptance criteria vary per instance, which is exactly the
part no generic client can guess.

Jira Cloud only (*.atlassian.net): email + API token, `/rest/api/3`. Jira Data
Center and Server are not supported - bind an Atlassian MCP tool your agent has
(`tools.jira: mcp:<tool>`) or your own script instead.

appqe never calls Jira itself; it names this script in `appqe.yml` under
`tools.jira` and the agent runs it. Credentials come from the environment, so
they never reach the framework or a config file.

The host and default project come from the project config's `tracker:` block,
so they are declared once and not restated per developer. Only the credentials
live in the environment - and the client loads them from the git-ignored
`env/.env` automatically, so you do not have to `source` it first:

    # env/.env  (git-ignored)
    JIRA_EMAIL=you@example.com
    JIRA_API_TOKEN=...                   # id.atlassian.com/manage-profile/security/api-tokens

An already-exported variable still wins, so `JIRA_EMAIL=other python3 ...` works
for a one-off.

The acceptance-criteria field id differs per Jira instance, so it is NOT
declared anywhere: the client discovers it by name from the instance's own field
metadata (see _ac_field). There is nothing to configure.

JIRA_BASE_URL / JIRA_PROJECT override the config if you need to point at another
instance for one command.

    python3 utilities/jira_client.py PROJ-123
    python3 utilities/jira_client.py 123               # -> $JIRA_PROJECT-123
    python3 utilities/jira_client.py --jql "sprint in openSprints()"   # scoped to $JIRA_PROJECT

Output is JSON on stdout so the agent can consume it directly.
"""

from __future__ import annotations

import argparse
import base64
import functools
import json
import os
import pathlib
import re
import sys
import urllib.error
import urllib.parse
import urllib.request
from typing import Any

TIMEOUT = 30


def _project_root() -> pathlib.Path | None:
    """The nearest folder above this script holding `appqe.yml`, else the repo root.

    One walk for both readers. The dotenv loader learned to walk (#126) while
    the config reader still looked at exactly `parent.parent`, so a client one
    folder deeper loaded its credentials and then said "No Jira host" beside a
    correctly filled `tracker.base_url`. A `.git` folder ends the walk, so it
    never reads another project's files.
    """
    for parent in pathlib.Path(__file__).resolve().parents:
        if (parent / "appqe.yml").is_file() or (parent / ".git").exists():
            return parent
    return None


def _load_dotenv() -> None:
    """Populate the environment from the project's git-ignored dotenv file.

    Without this, an agent that runs the client before `source`-ing env/.env sees
    "missing variable" and reports the system as unreachable - which it is not.
    An already-exported variable always wins: the file never overrides it.

    Walks UP to the project root rather than counting parents. A fixed
    `parent.parent` was a guess about a layout appqe does not control, and it
    was wrong the first time somebody's monorepo put this file four directories
    down: it looked in `services/bff-gateway/src/env/.env`, found nothing, and
    reported the credentials missing with a correctly-filled `env/.env` at the
    repo root. Moving the file fixed it with no code change, which is the tell.

    Bounded by a marker (`appqe.yml`, then `.git`) so the walk cannot climb OUT
    of the project and read a dotenv belonging to a parent directory - somebody
    else's credentials, silently. No marker found means no dotenv is loaded,
    and the variables have to come from the environment.
    """
    root = _project_root()
    if root is None:
        return
    for candidate in (root / "env" / ".env", root / ".env"):
        if not candidate.is_file():
            continue
        for raw in candidate.read_text(encoding="utf-8").splitlines():
            line = raw.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, _, value = line.partition("=")
            key = key.strip()
            if key and key not in os.environ:
                os.environ[key] = value.strip().strip('"').strip("'")


_load_dotenv()


def _tracker() -> dict[str, str]:
    """The tracker block from the project config: host and project.

    Declared once, in the file that already names the tracker, so these are not
    restated in every developer's environment and cannot drift out of step with
    the workflows that build issue keys from them. Credentials are never read
    here - see _credentials.
    """
    out: dict[str, str] = {}
    root = _project_root()
    config = root / "appqe.yml" if root is not None else None
    if config is not None and config.is_file():
        in_block = False
        for raw in config.read_text(encoding="utf-8").splitlines():
            if not raw.strip() or raw.lstrip().startswith("#"):
                continue
            if not raw[:1].isspace():
                in_block = raw.split(":", 1)[0].strip() == "tracker"
                continue
            if not in_block or ":" not in raw:
                continue
            key, _, value = raw.strip().partition(":")
            value = value.split("#", 1)[0].strip().strip("\"'")
            if key.strip() in ("base_url", "project_key") and value:
                out[key.strip()] = value
    return out


_CFG = _tracker()
_CFG_BASE = _CFG.get("base_url", "")
_CFG_PROJECT = _CFG.get("project_key", "")

# A bare issue number resolves against this, and a JQL query naming no project
# stays inside it rather than searching the whole instance and returning
# another team's issues. Environment wins, for a one-off against another site.
PROJECT = (os.environ.get("JIRA_PROJECT") or _CFG_PROJECT).strip().upper()


def _resolve_key(raw: str) -> str:
    """`PROJ-123` as given; a bare `123` against JIRA_PROJECT."""
    key = raw.strip().upper()
    if "-" in key:
        return key
    if not PROJECT:
        sys.exit(f"'{raw}' is not a full issue key and JIRA_PROJECT is unset. "
                 "Set JIRA_PROJECT (e.g. JIRA_PROJECT=PROJ) or pass PROJ-123.")
    return f"{PROJECT}-{key}"


def _scope(jql: str) -> str:
    """Confine a query to the default project unless it names one itself.

    An ORDER BY clause has to stay at the end, outside the parenthesised
    condition: `project = X AND (a ORDER BY b)` is a JQL syntax error, and
    wrapping blindly turned every sorted query into a 400.
    """
    if not PROJECT or "project" in jql.lower():
        return jql
    match = re.search(r"\border\s+by\b", jql, re.IGNORECASE)
    where = (jql[:match.start()] if match else jql).strip()
    order = (jql[match.start():] if match else "").strip()
    scoped = f"project = {PROJECT}" + (f" AND ({where})" if where else "")
    return f"{scoped} {order}".strip()


def _credentials() -> tuple[str, str, str]:
    """Host from config (or an override), identity and token from the environment.

    The token is never read from a file: this repo's config is committed, and a
    secret in it is a published secret.
    """
    base = (os.environ.get("JIRA_BASE_URL") or _CFG_BASE).rstrip("/")
    missing = [k for k in ("JIRA_EMAIL", "JIRA_API_TOKEN") if not os.environ.get(k)]
    if missing:
        sys.exit(f"Missing environment variable(s): {', '.join(missing)}. "
                 "Credentials come from the environment, never from a config file.")
    if not base:
        sys.exit("No Jira host. Set tracker.base_url in the project config, "
                 "or JIRA_BASE_URL for a one-off.")
    return base, os.environ["JIRA_EMAIL"], os.environ["JIRA_API_TOKEN"]


def _request(path: str, params: dict[str, str] | None = None) -> dict[str, Any]:
    """Raw GET. Raises HTTPError so a caller can try another endpoint."""
    base, email, token = _credentials()
    url = f"{base}{path}"
    if params:
        url += "?" + urllib.parse.urlencode(params)
    auth = base64.b64encode(f"{email}:{token}".encode()).decode()
    request = urllib.request.Request(url, headers={   # noqa: S310 - fixed https host
        "Authorization": f"Basic {auth}",
        "Accept": "application/json",
    })
    with urllib.request.urlopen(request, timeout=TIMEOUT) as response:  # noqa: S310
        data: dict[str, Any] = json.loads(response.read().decode("utf-8"))
        return data


#: Hosts that are certainly Atlassian Cloud. The same tuple sits in
#: confluence_client.py: the two disagreed (only this one knew `*.jira.com`), and
#: a test now holds them equal. Not a test of Cloud itself - a Cloud site can
#: live on a team's own domain - so a host outside it gets a conditional note.
CLOUD_HOSTS = (".atlassian.net", ".jira.com")


def _cloud_only_note(base: str) -> str:
    """What to do if the site is Data Center or Server, or "" when it is Cloud.

    This client speaks Jira Cloud only: email + API token, `/rest/api/3`. Jira
    Data Center and Server use personal access tokens and `/rest/api/2`, and
    against them this client got a bare 401 or 404 that read like a wrong key
    or a bad token. Data Center is deliberately not supported here, so the
    error says so and names the two ways that do work.

    Conditional, because the host cannot prove it: Atlassian Cloud also serves
    custom domains, and "does not look like Jira Cloud" told a Cloud team with
    a mistyped key that its product was unsupported.
    """
    host = (urllib.parse.urlparse(base).hostname or "").lower()
    if host.endswith(CLOUD_HOSTS):
        return ""
    return (f" Note: If {host or base} is Jira Data Center or Server, this client "
            "cannot read it: it supports Jira Cloud only. To read a Data Center or "
            "Server site, either bind an Atlassian MCP tool your agent already has "
            "(`tools.jira: mcp:<tool>` in appqe.yml), or bind your own script that "
            "speaks to it (`tools.jira: path/to/your_client.py`).")


def _get(path: str, params: dict[str, str] | None = None) -> dict[str, Any]:
    """GET that reports failure as a clear message rather than a traceback."""
    base = (os.environ.get("JIRA_BASE_URL") or _CFG_BASE).rstrip("/")
    try:
        return _request(path, params)
    except urllib.error.HTTPError as exc:
        sys.exit(f"Jira returned {exc.code} for {path}: "
                 f"{exc.read().decode('utf-8', 'replace')[:400]}"
                 + _cloud_only_note(base))
    except (urllib.error.URLError, TimeoutError) as exc:
        sys.exit(f"Could not reach Jira: {exc}" + _cloud_only_note(base))


@functools.lru_cache(maxsize=1)
def _ac_field() -> str:
    """The acceptance-criteria field id, discovered from the instance by NAME.

    The id (customfield_10001, _10267, ...) differs per Jira instance, so it is
    the one thing no generic client can hardcode - but the *name* is stable.
    /rest/api/3/field lists every field with its id and human name, so the
    client looks it up rather than making the human declare it. JIRA_AC_FIELD
    still forces a specific id when a site has more than one plausible match.

    Returns "" if nothing matches; _summarise then reports acceptance_criteria
    empty rather than guessing a wrong field.
    """
    forced = os.environ.get("JIRA_AC_FIELD")
    if forced:
        return forced
    try:
        fields = _request("/rest/api/3/field")
    except (urllib.error.URLError, urllib.error.HTTPError, TimeoutError):
        return ""
    named = [(str(f.get("name", "")).strip().lower(), str(f.get("id", "")))
             for f in fields if isinstance(f, dict)]
    # Exact name first, then a phrase match, then a loose one - so "Acceptance
    # Criteria" wins over "Acceptance test notes" when both exist.
    for predicate in (lambda n: n == "acceptance criteria",
                      lambda n: "acceptance criteria" in n,
                      lambda n: "acceptance" in n):
        hit = next((fid for name, fid in named if predicate(name)), "")
        if hit:
            return hit
    return ""


def _search_fields() -> str:
    """Fields to request for a search. The current search endpoint returns only
    issue ids unless asked, so an unspecified request yields every field blank."""
    base = ["summary", "status", "issuetype", "description", "labels",
            "components", "issuelinks"]
    ac = _ac_field()
    return ",".join([*base, ac] if ac else base)


def _search(jql: str, limit: int) -> list[dict[str, Any]]:
    """Run a JQL search across both generations of the Jira API.

    Cloud removed GET /rest/api/3/search (410, "please migrate to
    /rest/api/3/search/jql"), which silently broke every --jql query. A site
    not yet migrated has only the old path, so try the current one and fall
    back rather than picking one and being wrong on half the sites. (Data
    Center is not supported at all - see _cloud_only_note.)
    """
    params = {"jql": jql, "maxResults": str(limit), "fields": _search_fields()}
    try:
        data = _request("/rest/api/3/search/jql", params)
    except urllib.error.HTTPError as exc:
        if exc.code not in (404, 410):
            sys.exit(f"Jira returned {exc.code} for search: "
                     f"{exc.read().decode('utf-8', 'replace')[:400]}")
        data = _get("/rest/api/3/search", params)      # Server / Data Center
    except (urllib.error.URLError, TimeoutError) as exc:
        sys.exit(f"Could not reach Jira: {exc}")
    return [_summarise(i) for i in data.get("issues", [])]


def _plain_text(node: object) -> str:
    """Flatten Atlassian Document Format to text.

    Jira returns rich text as a nested document, not a string; without this the
    description arrives as unreadable JSON and the agent quotes the wrong thing.
    """
    if isinstance(node, str):
        return node
    if isinstance(node, list):
        return "".join(_plain_text(n) for n in node)
    if isinstance(node, dict):
        if node.get("type") == "hardBreak":
            return "\n"
        text = node.get("text", "")
        inner = _plain_text(node.get("content", []))
        suffix = "\n" if node.get("type") in ("paragraph", "listItem", "heading") else ""
        return f"{text}{inner}{suffix}"
    return ""


def _summarise(issue: dict[str, Any]) -> dict[str, Any]:
    fields = issue.get("fields", {}) or {}
    return {
        "key": issue.get("key", ""),
        "summary": fields.get("summary", ""),
        "status": (fields.get("status") or {}).get("name", ""),
        "type": (fields.get("issuetype") or {}).get("name", ""),
        "description": _plain_text(fields.get("description")).strip(),
        "acceptance_criteria": _plain_text(fields.get(_ac_field())).strip() if _ac_field() else "",
        "labels": fields.get("labels", []),
        "components": [c.get("name", "") for c in fields.get("components", []) or []],
        "links": [
            {"type": (link.get("type") or {}).get("name", ""),
             "key": (link.get("outwardIssue") or link.get("inwardIssue") or {}).get("key", "")}
            for link in fields.get("issuelinks", []) or []
        ],
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Fetch Jira context for test generation.")
    parser.add_argument("key", nargs="?",
                        help="Issue key (PROJ-123), or a bare number against JIRA_PROJECT")
    parser.add_argument("--jql", help="JQL query instead of a single key")
    parser.add_argument("--max", type=int, default=20, help="Max results for --jql")
    args = parser.parse_args(argv)

    if args.jql:
        issues = _search(_scope(args.jql), args.max)
    elif args.key:
        issues = [_summarise(_get(f"/rest/api/3/issue/{_resolve_key(args.key)}"))]
    else:
        parser.error("give an issue key or --jql")
        return 2

    json.dump({"issues": issues}, sys.stdout, indent=2)
    sys.stdout.write("\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
