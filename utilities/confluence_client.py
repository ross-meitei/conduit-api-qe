#!/usr/bin/env python3
"""Fetch a Confluence page's content, for QE test generation.

Generated by `appqe scaffold --tool confluence`. **This is a starter, not a
product** - it covers the read path QE needs (a page by id, by title, or by a
CQL search) and nothing else. Adapt it to your client's Confluence; storage
format in particular varies with the macros a space uses, and no generic client
flattens every one perfectly.

appqe never calls Confluence itself; it names this script in `appqe.yml` under
`tools.confluence` and the agent runs it. Credentials come from the environment,
so they never reach the framework or a config file.

Confluence Cloud usually lives on the same Atlassian site as Jira, so the host
and identity are shared by default:

  * host: a `confluence:` block in the project config (`base_url`), else the
    Jira host from `tracker.base_url` with `/wiki` appended.
  * credentials: `CONFLUENCE_EMAIL` / `CONFLUENCE_API_TOKEN` if set, otherwise
    the same `JIRA_EMAIL` / `JIRA_API_TOKEN` the Jira client uses. One Atlassian
    API token covers both products. Loaded from the git-ignored `env/.env`
    automatically - no need to `source` it first:

        # env/.env  (git-ignored)
        JIRA_EMAIL=you@example.com
        JIRA_API_TOKEN=...               # id.atlassian.com/manage-profile/security/api-tokens

`CONFLUENCE_BASE_URL` / `CONFLUENCE_SPACE` override the config for a one-off.

    python utilities/confluence_client.py 123456                 # a page by id
    python utilities/confluence_client.py --title "Retry semantics"
    python utilities/confluence_client.py --cql "text ~ 'idempotency'"
    python utilities/confluence_client.py --title "Auth rules" --space ENG

Output is JSON on stdout so the agent can consume it directly.
"""

from __future__ import annotations

import argparse
import base64
import html
import json
import os
import pathlib
import re
import sys
import urllib.error
import urllib.parse
import urllib.request
from typing import Any

TIMEOUT = 30


def _load_dotenv() -> None:
    """Populate the environment from the project's git-ignored dotenv file.

    So the client works whether or not the shell exported the credentials - an
    agent that forgot to `source env/.env` otherwise sees "missing credentials"
    and reports Confluence as unreachable, which it is not. An already-exported
    variable always wins; the file never overrides what is already set.
    """
    root = pathlib.Path(__file__).resolve().parent.parent
    for candidate in (root / "env" / ".env", root / ".env"):
        if not candidate.is_file():
            continue
        for raw in candidate.read_text(encoding="utf-8").splitlines():
            line = raw.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, _, value = line.partition("=")
            key = key.strip()
            if key and key not in os.environ:
                os.environ[key] = value.strip().strip('"').strip("'")


_load_dotenv()


def _yaml_block(name: str, keys: tuple[str, ...]) -> dict[str, str]:
    """Read a top-level block from the project config, without a YAML dependency.

    The same minimal reader the Jira client uses: a top-level key, then its
    indented `key: value` children, comments and quotes stripped. Kept here so
    the script stands alone - it is copied into the consumer project and must run
    with nothing installed but the standard library.
    """
    out: dict[str, str] = {}
    config = pathlib.Path(__file__).resolve().parent.parent / "appqe.yml"
    if not config.is_file():
        return out
    in_block = False
    for raw in config.read_text(encoding="utf-8").splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        if not raw[:1].isspace():
            in_block = raw.split(":", 1)[0].strip() == name
            continue
        if not in_block or ":" not in raw:
            continue
        key, _, value = raw.strip().partition(":")
        value = value.split("#", 1)[0].strip().strip("\"'")
        if key.strip() in keys and value:
            out[key.strip()] = value
    return out


_CONF = _yaml_block("confluence", ("base_url", "space_key"))
_TRACKER = _yaml_block("tracker", ("base_url",))

# Default space a title lookup or a bare CQL search is scoped to, so a search
# does not sweep the whole site and return another team's page. Environment wins.
SPACE = (os.environ.get("CONFLUENCE_SPACE") or _CONF.get("space_key", "")).strip()


def _base() -> str:
    """The Confluence REST root, ending in /wiki.

    Explicit `confluence.base_url` wins. Otherwise derive it from the Jira host,
    since Cloud serves both from one site: `https://x.atlassian.net` ->
    `https://x.atlassian.net/wiki`. An override is for pointing at another site
    for a single command.
    """
    explicit = (os.environ.get("CONFLUENCE_BASE_URL") or _CONF.get("base_url", "")).strip()
    if explicit:
        return explicit.rstrip("/")
    jira = _TRACKER.get("base_url", "").strip().rstrip("/")
    if not jira:
        sys.exit("No Confluence host. Set confluence.base_url in the project config "
                 "(e.g. https://your-org.atlassian.net/wiki), or CONFLUENCE_BASE_URL "
                 "for a one-off.")
    return jira if jira.endswith("/wiki") else f"{jira}/wiki"


def _credentials() -> tuple[str, str]:
    """Identity and token, from the Confluence vars or the shared Jira ones.

    Never read from a file: this repo's config is committed, and a secret in it
    is a published secret. One Atlassian token authenticates both products, so a
    project that already set the Jira vars needs nothing more.
    """
    email = os.environ.get("CONFLUENCE_EMAIL") or os.environ.get("JIRA_EMAIL")
    token = os.environ.get("CONFLUENCE_API_TOKEN") or os.environ.get("JIRA_API_TOKEN")
    if not email or not token:
        sys.exit("Missing credentials. Set CONFLUENCE_EMAIL + CONFLUENCE_API_TOKEN, "
                 "or the shared JIRA_EMAIL + JIRA_API_TOKEN. Credentials come from "
                 "the environment, never from a config file.")
    return email, token


def _request(path: str, params: dict[str, str] | None = None) -> dict[str, Any]:
    """Raw GET. Raises HTTPError so a caller can try another endpoint."""
    email, token = _credentials()
    url = f"{_base()}{path}"
    if params:
        url += "?" + urllib.parse.urlencode(params)
    auth = base64.b64encode(f"{email}:{token}".encode()).decode()
    request = urllib.request.Request(url, headers={   # noqa: S310 - fixed https host
        "Authorization": f"Basic {auth}",
        "Accept": "application/json",
    })
    with urllib.request.urlopen(request, timeout=TIMEOUT) as response:  # noqa: S310
        data: dict[str, Any] = json.loads(response.read().decode("utf-8"))
        return data


def _get(path: str, params: dict[str, str] | None = None) -> dict[str, Any]:
    """GET that reports failure as a clear message rather than a traceback."""
    try:
        return _request(path, params)
    except urllib.error.HTTPError as exc:
        sys.exit(f"Confluence returned {exc.code} for {path}: "
                 f"{exc.read().decode('utf-8', 'replace')[:400]}")
    except (urllib.error.URLError, TimeoutError) as exc:
        sys.exit(f"Could not reach Confluence: {exc}")


# Block-level tags whose close should become a line break, so the flattened text
# keeps the shape a reader (and the agent quoting it) depends on.
_BLOCK_CLOSE = re.compile(
    r"</(p|div|li|tr|h[1-6]|blockquote|pre)\s*>", re.IGNORECASE)
_CELL_CLOSE = re.compile(r"</(td|th)\s*>", re.IGNORECASE)
_LINE_BREAK = re.compile(r"<br\s*/?>", re.IGNORECASE)
_TAG = re.compile(r"<[^>]+>")


def _storage_to_text(storage: str) -> str:
    """Flatten Confluence storage format (XHTML + macros) to readable text.

    Storage format is not plain text: it is XHTML with `ac:`/`ri:` macro tags.
    Left raw, the agent quotes angle brackets instead of the rule. This keeps
    block structure - paragraphs and list items on their own lines, table cells
    separated - and drops the tags. It is deliberately simple; a space leaning on
    exotic macros is exactly where a starter needs adapting.
    """
    if not storage:
        return ""
    text = _LINE_BREAK.sub("\n", storage)
    text = _BLOCK_CLOSE.sub("\n", text)
    text = _CELL_CLOSE.sub(" | ", text)
    text = _TAG.sub("", text)
    text = html.unescape(text)
    # Collapse the runs of blank lines the tag removal leaves behind.
    text = re.sub(r"[ \t]+\n", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def _page_url(content: dict[str, Any]) -> str:
    """A browser link to the page, for citing it in a test."""
    links = content.get("_links", {}) or {}
    webui = links.get("webui", "")
    return f"{_base()}{webui}" if webui else ""


def _summarise(content: dict[str, Any]) -> dict[str, Any]:
    body = ((content.get("body") or {}).get("storage") or {}).get("value", "")
    space = (content.get("space") or {}).get("key", "") or \
            (content.get("space") or {}).get("name", "")
    return {
        "id": content.get("id", ""),
        "title": content.get("title", ""),
        "space": space,
        "version": (content.get("version") or {}).get("number", ""),
        "url": _page_url(content),
        "body": _storage_to_text(body),
    }


def _by_id(page_id: str) -> dict[str, Any]:
    return _summarise(_get(f"/rest/api/content/{page_id}",
                           {"expand": "body.storage,space,version"}))


def _search(cql: str, limit: int) -> list[dict[str, Any]]:
    """Run a CQL search, returning summarised pages with their bodies.

    The search endpoint returns matches without bodies unless asked, so
    `expand=body.storage` is required or every result comes back empty - the same
    trap the Jira search has with fields.
    """
    data = _get("/rest/api/content/search",
                {"cql": cql, "limit": str(limit), "expand": "body.storage,space,version"})
    return [_summarise(c) for c in data.get("results", [])]


def _scope_cql(cql: str) -> str:
    """Confine a query to the default space unless it names one itself."""
    if not SPACE or "space" in cql.lower():
        return cql
    return f"space = {SPACE} AND ({cql})"


def _title_cql(title: str) -> str:
    """CQL for a title lookup, scoped to the default space when there is one.

    `~` is a contains match, so a partial title still finds the page; an exact
    `title = "..."` would miss "Retry semantics (draft)".
    """
    safe = title.replace('"', '\\"')
    clause = f'type = page AND title ~ "{safe}"'
    return f"space = {SPACE} AND {clause}" if SPACE else clause


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Fetch Confluence context for test generation.")
    parser.add_argument("page_id", nargs="?", help="Page id to fetch directly")
    parser.add_argument("--title", help="Find a page by (partial) title")
    parser.add_argument("--cql", help="Raw CQL search, scoped to the default space")
    parser.add_argument("--space", help="Space key to scope --title/--cql to (overrides config)")
    parser.add_argument("--max", type=int, default=10, help="Max results for a search")
    args = parser.parse_args(argv)

    global SPACE
    if args.space:
        SPACE = args.space.strip()

    if args.page_id:
        pages = [_by_id(args.page_id)]
    elif args.title:
        pages = _search(_title_cql(args.title), args.max)
    elif args.cql:
        pages = _search(_scope_cql(args.cql), args.max)
    else:
        parser.error("give a page id, --title, or --cql")
        return 2

    json.dump({"pages": pages}, sys.stdout, indent=2)
    sys.stdout.write("\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
